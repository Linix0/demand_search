#!/usr/bin/env python3
"""Render deterministic Mermaid views from the canonical knowledge graph."""

from __future__ import annotations

import argparse
import json
import sys
from collections import defaultdict
from pathlib import Path
from typing import Any


REPO_ROOT = Path(__file__).resolve().parents[1]
GRAPH_DIR = REPO_ROOT / "docs" / "knowledge-graph"
GRAPH_PATH = GRAPH_DIR / "project-graph.json"
FULL_OUTPUT = GRAPH_DIR / "project-graph.mmd"
VIEW_DIR = GRAPH_DIR / "views"

VIEWS: dict[str, set[str] | None] = {
    "overview": {"goal", "principle", "decision", "component"},
    "requirements": {"requirement", "principle", "decision", "security_control"},
    "data": {"data_entity", "component", "technology"},
    "delivery": {"phase", "acceptance", "skill", "risk", "security_control"},
}

TYPE_LABELS = {
    "goal": "Goals",
    "principle": "Principles",
    "requirement": "Requirements",
    "decision": "Decisions",
    "technology": "Technology",
    "component": "Components",
    "data_entity": "Data entities",
    "security_control": "Security controls",
    "skill": "Codex skills",
    "phase": "Delivery phases",
    "acceptance": "Acceptance criteria",
    "artifact": "Artifacts",
    "risk": "Risks",
}

CLASS_DEFS = {
    "goal": "fill:#fff3bf,stroke:#b08900,color:#3d3200",
    "principle": "fill:#e7f5ff,stroke:#1971c2,color:#0b2e4f",
    "requirement": "fill:#f1f3f5,stroke:#495057,color:#212529",
    "decision": "fill:#e6fcf5,stroke:#087f5b,color:#0b3b2e",
    "technology": "fill:#f8f9fa,stroke:#868e96,color:#212529",
    "component": "fill:#f3f0ff,stroke:#6741d9,color:#2b1b5a",
    "data_entity": "fill:#fff0e6,stroke:#d9480f,color:#4a1b05",
    "security_control": "fill:#ffe3e3,stroke:#c92a2a,color:#4a0b0b",
    "skill": "fill:#e6fff8,stroke:#0b7285,color:#043b43",
    "phase": "fill:#edf2ff,stroke:#364fc7,color:#182558",
    "acceptance": "fill:#e7f5ff,stroke:#1c7ed6,color:#0b3c63",
    "artifact": "fill:#f5f5f5,stroke:#868e96,color:#333333",
    "risk": "fill:#fff5f5,stroke:#e03131,color:#4d0c0c",
}


def load_graph(path: Path = GRAPH_PATH) -> dict[str, Any]:
    with path.open(encoding="utf-8") as handle:
        return json.load(handle)


def _escape_label(value: str) -> str:
    return (
        value.replace("&", "&amp;")
        .replace('"', "#quot;")
        .replace("<", "&lt;")
        .replace(">", "&gt;")
        .replace("\n", "<br/>")
    )


def _node_alias_map(nodes: list[dict[str, Any]]) -> dict[str, str]:
    alias_by_id: dict[str, str] = {}
    used: set[str] = set()
    for index, node in enumerate(sorted(nodes, key=lambda item: item["id"]), start=1):
        base = "n" + "".join(character if character.isalnum() else "_" for character in node["id"])
        alias = base
        suffix = 2
        while alias in used:
            alias = f"{base}_{suffix}"
            suffix += 1
        used.add(alias)
        alias_by_id[node["id"]] = alias
    return alias_by_id


def render_view(graph: dict[str, Any], allowed_types: set[str] | None) -> str:
    nodes = [
        node
        for node in graph["nodes"]
        if allowed_types is None or node["type"] in allowed_types
    ]
    node_ids = {node["id"] for node in nodes}
    aliases = _node_alias_map(nodes)
    by_type: dict[str, list[dict[str, Any]]] = defaultdict(list)
    for node in nodes:
        by_type[node["type"]].append(node)

    lines = [
        "%% Generated by scripts/render_knowledge_graph.py; edit project-graph.json instead.",
        "flowchart LR",
    ]

    for node_type in sorted(by_type, key=lambda item: list(TYPE_LABELS).index(item)):
        type_nodes = sorted(by_type[node_type], key=lambda item: item["id"])
        label = _escape_label(TYPE_LABELS.get(node_type, node_type))
        lines.append(f'  subgraph sg_{node_type}["{label}"]')
        for node in type_nodes:
            alias = aliases[node["id"]]
            node_label = _escape_label(f"{node['id']}\n{node['title']}")
            lines.append(f'    {alias}["{node_label}"]')
        lines.append("  end")

    for edge in graph["edges"]:
        source = edge["from"]
        target = edge["to"]
        if source in node_ids and target in node_ids:
            lines.append(
                f'  {aliases[source]} -->|{_escape_label(edge["type"])}| {aliases[target]}'
            )

    for node_type in sorted(by_type, key=lambda item: list(TYPE_LABELS).index(item)):
        lines.append(f"  classDef {node_type} {CLASS_DEFS.get(node_type, '')}")

    for node_type in sorted(by_type, key=lambda item: list(TYPE_LABELS).index(item)):
        aliases_for_type = ",".join(
            aliases[node["id"]] for node in sorted(by_type[node_type], key=lambda item: item["id"])
        )
        lines.append(f"  class {aliases_for_type} {node_type}")

    return "\n".join(lines) + "\n"


def build_outputs(graph: dict[str, Any]) -> dict[Path, str]:
    outputs = {FULL_OUTPUT: render_view(graph, None)}
    for view_name, allowed_types in VIEWS.items():
        outputs[VIEW_DIR / f"{view_name}.mmd"] = render_view(graph, allowed_types)
    return outputs


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="Fail if generated views differ from the files on disk.",
    )
    args = parser.parse_args()

    try:
        graph = load_graph()
    except FileNotFoundError:
        print(f"Graph not found: {GRAPH_PATH}", file=sys.stderr)
        return 1
    except json.JSONDecodeError as exc:
        print(f"Invalid graph JSON: {exc}", file=sys.stderr)
        return 1

    outputs = build_outputs(graph)
    if args.check:
        problems: list[str] = []
        for path, expected in outputs.items():
            if not path.is_file():
                problems.append(f"Missing generated view: {path.relative_to(REPO_ROOT)}")
                continue
            actual = path.read_text(encoding="utf-8")
            if actual != expected:
                problems.append(f"Outdated generated view: {path.relative_to(REPO_ROOT)}")
        if problems:
            print("Knowledge graph render check failed:", file=sys.stderr)
            for problem in problems:
                print(f"  - {problem}", file=sys.stderr)
            return 1
        print(f"Knowledge graph render check passed for {len(outputs)} files.")
        return 0

    for path, content in outputs.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8", newline="\n")
        print(f"Wrote {path.relative_to(REPO_ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
